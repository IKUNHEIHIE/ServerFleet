#!/bin/sh
# Public HTTPS entry point. Downloaded helpers are independently digest-pinned;
# native installation still verifies the offline release signature and Root pin.
set -eu
umask 077
SF_SOURCE='https://raw.githubusercontent.com/IKUNHEIHIE/ServerFleet/v0.9.2/deployment'
SF_SETUP_SHA='ec20da041682768ad0acd5e8e4a8e74cc068e8683747a16343f853c809886e15'
SF_INSTALL_SHA='966c9a588e80b55d2218304002b866dc53bfa31f1a901936e2a31a4cea7c66dd'
MODE=${1:-help}
case "$MODE" in
 help|-h|--help)
  printf '%s\n' 'Server Fleet v0.9.2 installer' \
   '  download              Download verified release files for offline signing (ordinary user)' \
   '  setup                 Enable trusted Agent installation on an existing Controller (root)' \
   '  update-distribution   Upgrade an existing installer distribution (root)' \
   '  controller            Install a new Controller from a signed bundle and prepared config (root)' \
   '  agent [installer options]  Install Agent with the command generated by the console (root)' \
   'Configuration/token inputs are never evaluated as shell code. See deployment/RAW-INSTALL.md.'
  exit 0 ;;
 download|setup|update-distribution|controller|agent) shift ;;
 --*) MODE=agent ;;
 *) printf '%s\n' 'Unknown installation mode. Use --help.' >&2; exit 2 ;;
esac
[ "$(uname -s)" = Linux ] || { printf '%s\n' 'Linux is required.' >&2; exit 2; }
for command in curl sha256sum mktemp chmod uname; do
 command -v "$command" >/dev/null 2>&1 || { printf 'Missing prerequisite: %s\n' "$command" >&2; exit 2; }
done
case "$(uname -m)" in x86_64|amd64|aarch64|arm64) ;; *) printf '%s\n' 'Linux amd64/arm64 is required.' >&2; exit 2 ;; esac
SF_TEMP=$(mktemp -d)
trap 'rm -rf -- "$SF_TEMP"' EXIT HUP INT TERM
chmod 700 "$SF_TEMP"
get_helper() {
 curl --fail --silent --show-error --proto '=https' --tlsv1.3 --noproxy '*' \
  --max-time 90 --max-filesize 131072 "$SF_SOURCE/$1" --output "$SF_TEMP/$1"
 printf '%s  %s\n' "$2" "$SF_TEMP/$1" | sha256sum --check --status
 chmod 600 "$SF_TEMP/$1"
}
# In a curl|sh invocation use the controlling terminal for interactive prompts.
# Unattended enrollment instead uses the existing private token-file config.
SF_TTY=
if [ ! -t 0 ] && ( : </dev/tty ) 2>/dev/null; then SF_TTY=1; fi
run_helper() {
 if [ "$SF_TTY" = 1 ]; then "$@" </dev/tty; else "$@"; fi
}
case "$MODE" in
 agent)
  get_helper install.sh "$SF_INSTALL_SHA"
  run_helper sh "$SF_TEMP/install.sh" "$@" --component agent ;;
 *)
  command -v python3 >/dev/null 2>&1 || { printf '%s\n' 'Python 3 is required for Controller/distribution setup.' >&2; exit 2; }
  get_helper setup.py "$SF_SETUP_SHA"
  get_helper install.sh "$SF_INSTALL_SHA"
  case "$MODE" in
   download) run_helper python3 -I "$SF_TEMP/setup.py" fetch "$@" ;;
   setup) run_helper python3 -I "$SF_TEMP/setup.py" configure "$@" ;;
   update-distribution) run_helper python3 -I "$SF_TEMP/setup.py" update "$@" ;;
   controller) run_helper python3 -I "$SF_TEMP/setup.py" install-controller "$@" ;;
  esac ;;
esac
