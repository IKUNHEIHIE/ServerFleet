var ErrLinkRejected = errors.New("transport: connection rejected")
var ErrDeliveryUnknown = errors.New("transport: delivery unknown; reconcile execution, do not automatically retry")

// FrameSocket is implemented by the reviewed WSS adapter. Read MUST bound the
// frame before allocating; binary=false rejects text. Methods must honor ctx,
// support one concurrent reader/writer, and Close must unblock both. No SSH/raw
// TCP/JSON fallback is provided. TLSState must originate at the listener.
type FrameSocket interface {
	Read(context.Context) (binary bool, raw []byte, err error)
	Write(context.Context, []byte) error
	Close() error
}
type LinkObservation struct {
	Identity     AgentIdentity
	ConnectionID string
}
type ControllerLinkConfig struct {
	ProtocolMajor, ProtocolMinor uint32
	Semantic                     ValidationLimits
	Frames                       FrameDecodeLimits
	HeartbeatInterval            time.Duration
	MaxConnections               int
	// Trusted composition must resolve server capabilities, not echo the hello.
	Handshake func(context.Context, LinkObservation, *agentv1.AgentHello) ([]string, error)
	// Sole task admission: current authorization/approval/scope/plugin/task state.
	Admit func(context.Context, LinkObservation, *agentv1.Envelope) error
	// Persist domain event before returning; no default success callback.
	Event        func(context.Context, LinkObservation, *agentv1.Envelope) error
	Disconnected func(context.Context, LinkObservation) error
}
type ControllerLinks struct {
	mu       sync.Mutex
	links    map[string]*controllerLink
	verifier *PeerVerifier
	cfg      ControllerLinkConfig
}
type controllerLink struct {
	hub             *ControllerLinks
	socket          FrameSocket
	tls             tls.ConnectionState
	observed        LinkObservation
	incoming        *ConnectionGuard
	eventMu, sendMu sync.Mutex
	sequence        uint64
	active          bool // guarded by hub.mu
	granted         map[string]bool
}

func NewControllerLinks(verifier *PeerVerifier, cfg ControllerLinkConfig) (*ControllerLinks, error) {
	if verifier == nil || cfg.ProtocolMajor == 0 || cfg.MaxConnections <= 0 || cfg.MaxConnections > 10000 || cfg.Handshake == nil || cfg.Admit == nil || cfg.Event == nil || cfg.Disconnected == nil || cfg.HeartbeatInterval < time.Second || cfg.HeartbeatInterval > time.Minute || cfg.Frames.MaxFrameBytes <= 0 || cfg.Frames.MaxFrameBytes > 1<<20 || cfg.Frames.MaxFields <= 0 || cfg.Frames.MaxDepth <= 0 || cfg.Frames.MaxDepth > MaxSupportedFrameDepth {
		return nil, ErrLinkRejected
	}
	if cfg.Semantic.MaxMessageBytes <= 0 || cfg.Semantic.MaxMessageBytes > cfg.Frames.MaxFrameBytes || cfg.Semantic.MaxTextBytes <= 0 || cfg.Semantic.MaxParametersBytes <= 0 || cfg.Semantic.MaxOutputBytes <= 0 || cfg.Semantic.MaxMetrics <= 0 || cfg.Semantic.MaxSyncExecutions <= 0 || cfg.Semantic.MaxCapabilities <= 0 || cfg.Semantic.MaxTimeoutSeconds == 0 || cfg.Semantic.MaxOfferLifetime <= 0 || cfg.Semantic.MaxOfferLifetime > 15*time.Minute {
		return nil, ErrLinkRejected
	}
	actions := map[string]string{}
	for k, v := range cfg.Semantic.AllowedActions {
		actions[k] = v
	}
	cfg.Semantic.AllowedActions = actions
	return &ControllerLinks{links: map[string]*controllerLink{}, verifier: verifier, cfg: cfg}, nil
}
func (h *ControllerLinks) current(l *controllerLink) bool {
	h.mu.Lock()
	defer h.mu.Unlock()
	return l.active && h.links[l.observed.Identity.NodeID] == l
}
func (h *ControllerLinks) validation(direction Direction, phase HandshakePhase) ValidationContext {
	return ValidationContext{Direction: direction, Phase: phase, ProtocolMajor: h.cfg.ProtocolMajor, ProtocolMinor: h.cfg.ProtocolMinor, Now: time.Now()}
}
func randomLinkID() (string, error) {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", ErrLinkRejected
	}
	return hex.EncodeToString(b[:]), nil
}
func NewConnectionID() (string, error) { return randomLinkID() }

// Serve blocks for one Agent-initiated authenticated WSS connection. connectionID
// is unique and generated by the trusted upgrader (e.g. upgrade response header),
// never taken from an inbound frame. Reconnect creates a new ID and sequence.
func (h *ControllerLinks) Serve(ctx context.Context, socket FrameSocket, state tls.ConnectionState, connectionID string) (err error) {
	if h == nil || ctx == nil || socket == nil || !validBindingID(connectionID) || len(connectionID) > 128 {
		return ErrLinkRejected
	}
	defer socket.Close()
	identity, err := h.verifier.Verify(ctx, state, "")
	if err != nil {
		return ErrLinkRejected
	}
	guard, err := NewConnectionGuard(ConnectionBinding{identity.NodeID, connectionID, AgentToController})
	if err != nil {
		return ErrLinkRejected
	}
	defer guard.Close()
	l := &controllerLink{hub: h, socket: socket, tls: state, observed: LinkObservation{identity, connectionID}, incoming: guard}
	handshakeCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	binary, raw, err := socket.Read(handshakeCtx)
	if err != nil || !binary {
		cancel()
		return ErrLinkRejected
	}
	hello, err := guard.Receive(raw, h.validation(AgentToController, AwaitAgentHello), h.cfg.Semantic, h.cfg.Frames)
	if err != nil {
		cancel()
		return ErrLinkRejected
	}
	current, err := h.verifier.Verify(handshakeCtx, state, hello.NodeId)
	if err != nil || current.TrustGeneration != identity.TrustGeneration {
		cancel()
		return ErrLinkRejected
	}
	caps, err := h.cfg.Handshake(handshakeCtx, l.observed, proto.Clone(hello.GetAgentHello()).(*agentv1.AgentHello))
	if err != nil || len(caps) > h.cfg.Semantic.MaxCapabilities {
		cancel()
		return ErrLinkRejected
	}
	seen := map[string]bool{}
	for _, cap := range caps {
		if seen[cap] || h.cfg.Semantic.AllowedActions[cap] == "" || !slices.Contains(hello.GetAgentHello().CapabilityIds, cap) {
			cancel()
			return ErrLinkRejected
		}
		seen[cap] = true
	}
	l.granted = seen
	reply := &agentv1.Envelope{Message: &agentv1.Envelope_ControllerHello{ControllerHello: &agentv1.ControllerHello{Accepted: true, SelectedProtocolMajor: h.cfg.ProtocolMajor, SelectedProtocolMinor: h.cfg.ProtocolMinor, GrantedCapabilityIds: append([]string{}, caps...), HeartbeatIntervalSeconds: uint32(h.cfg.HeartbeatInterval / time.Second), MaxFrameBytes: uint32(h.cfg.Frames.MaxFrameBytes), ServerTimeUnixMs: time.Now().UnixMilli()}}}
	err = h.activate(handshakeCtx, l, reply)
	cancel()
	if err != nil {
		return err
	}
	defer func() {
		l.eventMu.Lock()
		defer l.eventMu.Unlock()
		h.mu.Lock()
		current := h.links[identity.NodeID] == l
		if current {
			delete(h.links, identity.NodeID)
		}
		l.active = false
		h.mu.Unlock()
		if current {
			offline, cancel := context.WithTimeout(context.WithoutCancel(ctx), 3*time.Second)
			defer cancel()
			if h.cfg.Disconnected(offline, l.observed) != nil {
				err = ErrLinkRejected
			}
		}
	}()
	if err = l.deliver(ctx, hello); err != nil {
		return err
	}
	for {
		readCtx, cancel := context.WithTimeout(ctx, 3*h.cfg.HeartbeatInterval)
		binary, raw, err = socket.Read(readCtx)
		cancel()
		if err != nil || !binary {
			return ErrLinkRejected
		}
		envelope, decodeErr := guard.Receive(raw, h.validation(AgentToController, Established), h.cfg.Semantic, h.cfg.Frames)
		if decodeErr != nil {
			return ErrLinkRejected
		}
		if err = l.deliver(ctx, envelope); err != nil {
			return err
		}
	}
}

// Event and send locks serialize replacement with callbacks/writes, without
// holding the registry lock across application or socket I/O. A callback may
// submit through Send; it must cooperate with cancellation and never call Serve.
func (h *ControllerLinks) activate(ctx context.Context, l *controllerLink, hello *agentv1.Envelope) error {
	for {
		h.mu.Lock()
		old := h.links[l.observed.Identity.NodeID]
		h.mu.Unlock()
		if old != nil {
			old.eventMu.Lock()
			old.sendMu.Lock()
		}
		l.sendMu.Lock()
		h.mu.Lock()
		if old == nil && len(h.links) >= h.cfg.MaxConnections {
			h.mu.Unlock()
			l.sendMu.Unlock()
			return ErrLinkRejected
		}
		if h.links[l.observed.Identity.NodeID] != old {
			h.mu.Unlock()
			l.sendMu.Unlock()
			if old != nil {
				old.sendMu.Unlock()
				old.eventMu.Unlock()
			}
			continue
		}
		if old != nil {
			old.active = false
		}
		h.links[l.observed.Identity.NodeID] = l
		l.active = true
		h.mu.Unlock()
		err := l.write(ctx, hello, AwaitControllerHello)
		l.sendMu.Unlock()
		if old != nil {
			old.sendMu.Unlock()
			old.eventMu.Unlock()
			_ = old.socket.Close()
		}
		if err != nil {
			h.mu.Lock()
			if h.links[l.observed.Identity.NodeID] == l {
				delete(h.links, l.observed.Identity.NodeID)
			}
			l.active = false
			h.mu.Unlock()
			return err
		}
		return nil
	}
}
func (l *controllerLink) deliver(ctx context.Context, envelope *agentv1.Envelope) error {
	l.eventMu.Lock()
	defer l.eventMu.Unlock()
	if !l.hub.current(l) {
		return ErrLinkRejected
	}
	id, err := l.hub.verifier.Verify(ctx, l.tls, envelope.NodeId)
	if err != nil || id != l.observed.Identity {
		return ErrLinkRejected
	}
	if l.hub.cfg.Event(ctx, l.observed, envelope) != nil {
		return ErrLinkRejected
	}
	return nil
}
func (l *controllerLink) write(ctx context.Context, envelope *agentv1.Envelope, phase HandshakePhase) error {
	id, err := l.hub.verifier.Verify(ctx, l.tls, l.observed.Identity.NodeID)
	if err != nil || id != l.observed.Identity {
		return ErrLinkRejected
	}
	idText, err := randomLinkID()
	if err != nil {
		return err
	}
	l.sequence++
	if l.sequence == 0 {
		return ErrLinkRejected
	}
	envelope.MessageId = idText
	envelope.ConnectionId = l.observed.ConnectionID
	envelope.NodeId = id.NodeID
	envelope.Sequence = l.sequence
	envelope.ProtocolMajor = l.hub.cfg.ProtocolMajor
	envelope.ProtocolMinor = l.hub.cfg.ProtocolMinor
	envelope.SentAtUnixMs = time.Now().UnixMilli()
	if ValidateEnvelope(envelope, l.hub.validation(ControllerToAgent, phase), l.hub.cfg.Semantic) != nil {
		return ErrLinkRejected
	}
	raw, err := proto.Marshal(envelope)
	if err != nil || len(raw) > l.hub.cfg.Frames.MaxFrameBytes {
		return ErrLinkRejected
	}
	writeCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	if l.socket.Write(writeCtx, raw) != nil {
		_ = l.socket.Close()
		return ErrDeliveryUnknown
	}
	return nil
}

// Send implements the existing Sender. A successful socket write is delivery
// evidence only, never task success. Failed writes may already have reached the
// Agent; Controller must reconcile the SAME execution ID, never blind requeue.
func (h *ControllerLinks) Send(ctx context.Context, node string, envelope *agentv1.Envelope) error {
	if h == nil || ctx == nil || ctx.Err() != nil || envelope == nil {
		return ErrLinkRejected
	}
	detached := proto.Clone(envelope).(*agentv1.Envelope)
	h.mu.Lock()
	l := h.links[node]
	h.mu.Unlock()
	if l == nil {
		return ErrLinkRejected
	}
	l.sendMu.Lock()
	defer l.sendMu.Unlock()
	if !h.current(l) {
		return ErrLinkRejected
	}
	if detached.GetControllerHello() != nil || detached.GetAgentHello() != nil {
		return ErrLinkRejected
	}
	if offer := detached.GetTaskOffer(); offer != nil && !l.granted[offer.ActionId] {
		return ErrLinkRejected
	}
	id, err := h.verifier.Verify(ctx, l.tls, node)
	if err != nil || id != l.observed.Identity {
		return ErrLinkRejected
	}
	if h.cfg.Admit(ctx, l.observed, proto.Clone(detached).(*agentv1.Envelope)) != nil {
		return ErrLinkRejected
	}
	return l.write(ctx, detached, Established)
}

var _ Sender = (*ControllerLinks)(nil)
